"""Тестовый модуль 1: выводит сообщения в консоль.

Лаунчер находит этот файл, создаёт для него кнопку и при нажатии
вызывает функцию run().
"""

import time


def run():
    """Главная функция модуля. Вызывается лаунчером."""
    print("=== example_one запущен ===")
    for i in range(1, 6):
        print(f"  Шаг {i} из 5...")
        time.sleep(0.4)
    print("=== example_one завершён ===")


if __name__ == "__main__":
    # Позволяет запускать модуль и напрямую: python apps/example_one.py
    run()
